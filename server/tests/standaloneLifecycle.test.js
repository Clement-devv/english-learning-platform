import { it, expect } from 'vitest';
import mongoose from 'mongoose';
import { bookingSchema } from '../schemas/bookingSchema.js';
import { groupClassSchema } from '../schemas/groupClassSchema.js';
import { classroomSessionSchema } from '../schemas/classroomSessionSchema.js';
import { completeStandaloneLesson, uncompleteStandaloneLesson, sweepUnattendedStandaloneLessons } from '../services/standaloneLessonService.js';
const oid = () => new mongoose.Types.ObjectId();
const model = (db,n,s) => db.models[n] || db.model(n,s);
it('moves unattended individual and group classes at their exact scheduled end, preserving future and joined lessons', async () => {
  const db=global.__TEST_DB__.useDb('lifecycle-sweep',{useCache:true});
  const Booking=model(db,'Booking',bookingSchema),Group=model(db,'GroupClass',groupClassSchema),Session=model(db,'ClassroomSession',classroomSessionSchema);
  const base={teacherId:oid(),studentId:oid(),managedCenterId:oid(),classTitle:'Unattended',scheduledTime:new Date('2026-11-10T22:00:00Z'),duration:30,status:'accepted',standalonePay:{currency:'USD',amountMinor:2000}};
  const missed=await Booking.create(base),future=await Booking.create({...base,scheduledTime:new Date('2026-11-10T23:00:00Z')}),joined=await Booking.create(base);
  await Session.create({bookingId:joined._id,requiredTime:1500,teacherJoinedAt:new Date('2026-11-10T22:01:00Z')});
  const group=await Group.create({...base,title:'Unattended group',status:'open'});
  expect(await sweepUnattendedStandaloneLessons(db,new Date('2026-11-10T22:29:59Z'))).toBe(0);
  expect(await sweepUnattendedStandaloneLessons(db,new Date('2026-11-10T22:30:00Z'))).toBe(2);
  expect((await Booking.findById(missed._id)).missedReason).toContain('No one joined');
  expect((await Group.findById(group._id)).status).toBe('missed');
  expect((await Booking.findById(future._id)).status).toBe('accepted');
  expect((await Booking.findById(joined._id)).status).toBe('accepted');
  expect(await sweepUnattendedStandaloneLessons(db,new Date('2026-11-10T22:31:00Z'))).toBe(0);
});
it.each([false,true])('reverses only recorded credits once and supports marking taught again (group=%s)',async(group)=>{
  const db=global.__TEST_DB__.useDb(`lifecycle-reverse-${group}`,{useCache:true});
  const teacherId=oid(),studentId=oid(),absentId=oid();
  await db.collection('teachers').insertOne({_id:teacherId,lessonsCompleted:0});
  await db.collection('students').insertMany([{_id:studentId,standaloneManaged:true,classCredits:3},{_id:absentId,standaloneManaged:true,classCredits:3}]);
  const Class=model(db,group?'GroupClass':'Booking',group?groupClassSchema:bookingSchema);
  let lesson=await Class.create({teacherId,studentId,managedCenterId:oid(),classTitle:'Lesson',title:'Lesson',scheduledTime:new Date(),duration:30,status:'missed',standalonePay:{currency:'USD',amountMinor:2000,credits:true},...(group?{enrollments:[{studentId,attendance:'attended'},{studentId:absentId,attendance:'absent'}]}:{})});
  await completeStandaloneLesson(db,lesson,teacherId);
  lesson=await Class.findById(lesson._id);
  expect((await db.collection('students').findOne({_id:studentId})).classCredits).toBe(2);
  expect((await db.collection('students').findOne({_id:absentId})).classCredits).toBe(3);
  await uncompleteStandaloneLesson(db,lesson,teacherId,'Recorded by mistake');
  lesson=await Class.findById(lesson._id);
  expect(lesson.status).toBe('missed');expect(lesson.missedReason).toBe('Recorded by mistake');
  await uncompleteStandaloneLesson(db,lesson,teacherId);
  expect((await db.collection('students').findOne({_id:studentId})).classCredits).toBe(3);
  expect((await db.collection('teachers').findOne({_id:teacherId})).lessonsCompleted).toBe(0);
  await completeStandaloneLesson(db,lesson,teacherId,group?[{studentId,status:'attended'},{studentId:absentId,status:'absent'}]:undefined);
  expect((await db.collection('students').findOne({_id:studentId})).classCredits).toBe(2);
});
